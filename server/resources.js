// שדות שמותר לכתוב לכל משאב (נגזר מההגדרה) + שדות אוטומטיים
export function writableFields(res) {
  const keys = res.fields.map((f) => f.key);
  if (res.autoUser) keys.push(res.autoUser);
  return keys;
}

export function publicMeta() {
  const out = {};
  for (const [key, r] of Object.entries(RESOURCES)) {
    out[key] = {
      key,
      label: r.label,
      one: r.one,
      icon: r.icon,
      fields: r.fields,
      readonlyFields: r.readonlyFields || [],
      list: r.list,
      filters: r.filters || [],
      detailPath: r.detailPath,
      readonly: !!r.readonly,
      computed: Object.keys(r.computed || {}),
      perms: r.perms,
    };
  }
  return { resources: out, options: OPTIONS };
}
